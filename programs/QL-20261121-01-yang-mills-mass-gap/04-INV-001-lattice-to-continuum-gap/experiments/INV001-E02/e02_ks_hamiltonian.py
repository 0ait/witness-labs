"""INV001-E02: exact diagonalization of Kogut-Susskind Hamiltonians (lattice units a=1).

Part A: SU(2) single plaquette (open, 4 links, 4 vertices).
  H = (g^2/2) sum_{l=1..4} E_l^2 - (1/g^2)(Tr U_p + Tr U_p^dag).
  Gauss law at the 4 bivalent vertices => gauge-invariant space = class functions of U_p,
  basis chi_j(U_p), j = 0,1/2,1,..., each link in irrep j: sum E_l^2 -> 4 j(j+1).
  Tr U_p = chi_{1/2};  chi_{1/2} chi_j = chi_{j+1/2} + chi_{j-1/2};  Tr U^dag = Tr U for SU(2).
  => tridiagonal: H_jj = 2 g^2 j(j+1), H_{j,j+-1/2} = -2/g^2 ; truncation j <= jmax.
  Independent check: reduced radial problem u(th) = sin(th) f(th), Dirichlet on [0,pi]:
     -(g^2/2)(u''+u) - (4/g^2) cos(th) u = E u   (Mathieu; E_n = (g^2/8) b_{2n+2}(16/g^4) - g^2/2)
  solved (a) with scipy.special.mathieu_b and (b) with a sine-spectral (Galerkin) discretisation.
Part B: Z_2 lattice gauge theory on a periodic ladder of n plaquettes (2n vertices, 3n links).
  H = h sum_l (1 - sigma^x_l) - J sum_p prod_{l in p} sigma^z_l.
  Gauge-invariant states (Gauss law: prod of sigma^x around each vertex = +1) = Z_2 cycle space of
  the ladder graph (dim n+1): 2^{n+1} states; electric energy 2h*|c|, plaquette term flips c by dp.
  Sectors: winding w = c(t_1)+c(b_1) mod 2 (homology of the annulus), invariant under H.
  w=0 contains the vacuum and all states generated by contractible loops ('local sector');
  w=1 is the 'torelon' sector (flux around the ring).
  Independent check for small n: full 2^{3n}-dimensional Hilbert space with explicit Gauss-law projector.
"""
import numpy as np, json, scipy.sparse as sp, scipy.sparse.linalg as sla, scipy.special as ss, itertools, time
out = {}
# ---------------- Part A
def plaquette_H(g2, jmax2):
    js = np.arange(0, jmax2+1)/2.0
    H = np.diag(2*g2*js*(js+1))
    off = -2.0/g2*np.ones(len(js)-1)
    return H + np.diag(off,1) + np.diag(off,-1)
def galerkin_H(g2, N):
    # basis s_k(th) = sqrt(2/pi) sin(k th), k=1..N on [0,pi]; -(g2/2)(u''+u) diag: (g2/2)(k^2-1)
    k = np.arange(1, N+1)
    H = np.diag(g2/2*(k**2-1.0))
    # <s_k| cos th |s_l> = 1/2 (delta_{k,l+1}+delta_{k,l-1})
    off = -(4.0/g2)*0.5*np.ones(N-1)
    return H + np.diag(off,1) + np.diag(off,-1)
A = []
for g2 in [8.0, 4.0, 2.0, 1.0, 0.5, 0.25, 0.1, 0.05]:
    row = dict(g2=g2)
    conv = []
    for jmax2 in [2,4,8,16,32,64,128]:
        ev = np.linalg.eigvalsh(plaquette_H(g2, jmax2))
        conv.append((jmax2/2, ev[1]-ev[0]))
    row['gap_vs_jmax'] = conv
    evG = np.linalg.eigvalsh(galerkin_H(g2, 400))
    row['gap_galerkin400'] = evG[1]-evG[0]
    q = 16.0/g2**2
    try:
        b2, b4 = ss.mathieu_b(2, q), ss.mathieu_b(4, q)
        row['gap_mathieu'] = (g2/8)*(b4-b2)
    except Exception as e:
        row['gap_mathieu'] = str(e)
    row['E0_tridiag'] = float(np.linalg.eigvalsh(plaquette_H(g2,128))[0])
    row['E0_galerkin'] = float(evG[0])
    row['strong_coupling_leading'] = 1.5*g2      # 2 g^2 * (1/2)(3/2)
    A.append(row)
    print('g2=%.3f gap(jmax=64)=%.12f galerkin=%.12f mathieu=%s' % (g2, conv[-1][1], row['gap_galerkin400'], row['gap_mathieu']))
out['su2_single_plaquette'] = A
# ---------------- Part B
def ladder_links(n):
    # link indices: top t_i = i, bottom b_i = n+i, rung r_i = 2n+i ; vertices top (i), bottom (n+i)
    plaq = [[i, n+i, 2*n+i, 2*n+(i+1)%n] for i in range(n)]
    return plaq
def ladder_H_gaugeinv(n, h, J):
    plaq = ladder_links(n)
    pm = [sum(1<<l for l in p) for p in plaq]
    top = sum(1<<i for i in range(n))
    # enumerate cycle space: c = sum eps_i dp_i + w*top
    states = []
    for bits in range(1<<(n+1)):
        c = 0
        for i in range(n):
            if bits>>i & 1: c ^= pm[i]
        if bits>>n & 1: c ^= top
        states.append(c)
    idx = {c:k for k,c in enumerate(states)}
    assert len(idx) == len(states)  # independence of generators
    D = len(states)
    diag = np.array([2*h*bin(c).count('1') for c in states], float)
    rows, cols = [], []
    for k,c in enumerate(states):
        for m in pm:
            rows.append(idx[c^m]); cols.append(k)
    Hm = sp.csr_matrix((-J*np.ones(len(rows)), (rows, cols)), shape=(D,D))
    H = Hm + sp.diags(diag)
    wind = np.array([((c>>0)&1) ^ ((c>>n)&1) for c in states])
    return H, wind, states
def lowest(H, k):
    D = H.shape[0]
    if D <= 600:
        return np.sort(np.linalg.eigvalsh(H.toarray()))[:k]
    return np.sort(sla.eigsh(H, k=k, which='SA', tol=1e-12)[0])
def ladder_spectrum(n, h, J):
    H, wind, _ = ladder_H_gaugeinv(n, h, J)
    res = {}
    for w in [0,1]:
        sel = np.where(wind==w)[0]
        Hw = H[sel][:,sel]
        res[w] = lowest(Hw, 3)
    E0 = res[0][0]
    return dict(n=n, h=h, J=J, E0=E0, local_gap=res[0][1]-E0, torelon_gap=res[1][0]-E0,
                full_gap=min(res[0][1], res[1][0])-E0, ground_in_w0=bool(res[0][0] <= res[1][0]))
# brute-force check for small n with explicit Gauss projector
def ladder_full_check(n, h, J):
    nl = 3*n; D = 1<<nl
    plaq = ladder_links(n)
    # vertices: top i touches t_{i-1}, t_i, r_i ; bottom i touches b_{i-1}, b_i, r_i
    verts = [[(i-1)%n, i, 2*n+i] for i in range(n)] + [[n+(i-1)%n, n+i, 2*n+i] for i in range(n)]
    # work in sigma^x eigenbasis: basis bit=1 means sigma^x=-1 (flux). sigma^z flips bit.
    diag = np.array([2*h*bin(s).count('1') for s in range(D)], float)
    rows, cols = [], []
    for s in range(D):
        for p in plaq:
            m = sum(1<<l for l in p); rows.append(s^m); cols.append(s)
    H = sp.csr_matrix((-J*np.ones(len(rows)), (rows, cols)), shape=(D,D)) + sp.diags(diag)
    # Gauss law: product of sigma^x over links at vertex = +1  <=> even number of flux bits at vertex
    phys = [s for s in range(D) if all(sum((s>>l)&1 for l in v)%2==0 for v in verts)]
    Hp = H[phys][:,phys].toarray()
    ev = np.sort(np.linalg.eigvalsh(Hp))
    return len(phys), ev[:4]
checks = []
for n in [3,4]:
    for (h,J) in [(1.0,0.5),(1.0,2.0),(0.3,1.0)]:
        dimp, evf = ladder_full_check(n,h,J)
        H,_,_ = ladder_H_gaugeinv(n,h,J)
        evg = np.sort(np.linalg.eigvalsh(H.toarray()))[:4]
        checks.append(dict(n=n,h=h,J=J,phys_dim=dimp,gaugeinv_dim=H.shape[0],maxdiff=float(np.max(abs(evf-evg)))))
        print('ladder check', checks[-1])
out['ladder_crosscheck_full_vs_gaugeinv'] = checks
B = []
for (h,J) in [(1.0,0.25),(1.0,1.0),(1.0,2.0),(1.0,4.0)]:
    for n in [4,6,8,10,12,14,16]:
        t0=time.time()
        r = ladder_spectrum(n,h,J); r['sec']=round(time.time()-t0,2)
        B.append(r); print(r)
out['z2_ladder'] = B
json.dump(out, open('outputs/e02_results.json','w'), indent=1, default=float)
